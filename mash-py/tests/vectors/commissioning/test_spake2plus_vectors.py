def test_every_vector_has_a_test() -> None:
    file_ids = {v["id"] for v in VECTORS}
    missing = file_ids - _HANDLED_IDS
    extra = _HANDLED_IDS - file_ids
    assert not missing, (
        f"vectors present in JSON but no Python test: {sorted(missing)}. "
        "Add a test in test_spake2plus_vectors.py for each new id."
    )
    assert not extra, f"tests reference removed vector ids: {sorted(extra)}."


def test_verifier_dataclass_is_frozen() -> None:
    """``Verifier`` is an immutable record -- it lives in NVS in production."""
    from dataclasses import FrozenInstanceError

    v = generate_verifier("20202021", 3840, iterations=1000)
    with pytest.raises(FrozenInstanceError):
        v.discriminator = 0  # type: ignore[misc]
    # And construction yields the protocol-required field sizes.
    assert isinstance(v, Verifier)
    assert len(v.salt) == 16
    assert len(v.w0) == 32
    assert len(v.L) == 65
