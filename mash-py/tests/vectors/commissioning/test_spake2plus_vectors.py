# ---------------------------------------------------------------------------
# End-to-end vector (full handshake from setup_code + discriminator)
# ---------------------------------------------------------------------------


def test_full_handshake() -> None:
    v = _vector_by_id("full_handshake")
    inp = v["inputs"]
    out = v["outputs"]

    # §2.3: salt, MHF, w0/w1, L  (via generate_verifier)
    verifier = generate_verifier(
        inp["setup_code"], inp["discriminator"], iterations=inp["iterations"]
    )
    assert verifier.salt.hex() == out["salt_hex"]
    assert verifier.w0.hex() == out["w0_hex"]
    assert verifier.L.hex() == out["L_hex"]

    # Independently re-derive mhf_out / w1 to compare the intermediate.
    mhf_out = pbkdf2_mhf(
        inp["setup_code"].encode("utf-8"),
        verifier.salt,
        iterations=inp["iterations"],
    )
    assert mhf_out.hex() == out["mhf_out_hex"]
    w0_int, w1_int = derive_w0_w1(mhf_out)
    assert scalar_to_bytes(w1_int).hex() == out["w1_hex"]

    # §2.4: public values with fixed x, y (deterministic vector).
    x_int = int.from_bytes(bytes.fromhex(inp["x_hex"]), "big")
    y_int = int.from_bytes(bytes.fromhex(inp["y_hex"]), "big")
    pA = client_public(w0_int, x_int)
    pB = server_public(w0_int, y_int)
    assert pA.hex() == out["pA_hex"]
    assert pB.hex() == out["pB_hex"]

    # Drive the state machines with the fixed scalars and verify the
    # full key chain (this exercises the same code paths the eventual
    # PASE driver will hit in Phase 8).
    from mash_py.commissioning.spake2plus import SPAKE2PlusClient, SPAKE2PlusServer

    client = SPAKE2PlusClient(
        inp["setup_code"], inp["discriminator"], iterations=inp["iterations"], x=x_int
    )
    server = SPAKE2PlusServer(verifier, y=y_int)

    assert client.public_value().hex() == out["pA_hex"]
    assert server.public_value().hex() == out["pB_hex"]

    server.process_client_value(pA)
    client.process_server_value(pB)

    assert client.shared_secret.hex() == out["K_main_hex"]
    assert server.shared_secret.hex() == out["K_main_hex"]
    assert client.encryption_key.hex() == out["K_encrypt_hex"]
    assert server.encryption_key.hex() == out["K_encrypt_hex"]

    # Confirmation MACs match the vector and verify both directions.
    confirmA = client.confirmation()
    confirmB = server.confirmation()
    assert confirmA.hex() == out["confirmA_hex"]
    assert confirmB.hex() == out["confirmB_hex"]
    server.verify_client_confirmation(confirmA)
    client.verify_server_confirmation(confirmB)

    # Independently verify the transcript / K_shared / key chain paths
    # so a mismatch at any one stage points to the failing primitive.
    M_bytes = encode_point_uncompressed(SPAKE2_M)
    N_bytes = encode_point_uncompressed(SPAKE2_N)
    Z_bytes = bytes.fromhex(out["Z_hex"])
    V_bytes = bytes.fromhex(out["V_hex"])
    TT = compose_transcript(
        b"mash-controller",
        b"mash-device",
        M_bytes,
        N_bytes,
        pA,
        pB,
        Z_bytes,
        V_bytes,
        scalar_to_bytes(w0_int),
    )
    assert TT.hex() == out["TT_hex"]
    K = k_shared(TT)
    assert K.hex() == out["K_shared_hex"]
    K_main, K_confirm, K_encrypt = key_chain(K)
    assert K_main.hex() == out["K_main_hex"]
    assert K_confirm.hex() == out["K_confirm_hex"]
    assert K_encrypt.hex() == out["K_encrypt_hex"]
    KcA, KcB = confirmation_keys(K_confirm)
    assert KcA.hex() == out["KcA_hex"]
    assert KcB.hex() == out["KcB_hex"]


