def test_mhf_basic() -> None:
    v = _vector_by_id("mhf_basic")
    inp = v["inputs"]
    out = pbkdf2_mhf(
        inp["setup_code"].encode("utf-8"),
        bytes.fromhex(inp["salt_hex"]),
        iterations=inp["iterations"],
        dklen=inp["dklen"],
    )
    assert out.hex() == v["outputs"]["mhf_out_hex"]


def test_derive_w0_w1() -> None:
    v = _vector_by_id("derive_w0_w1")
    mhf_out = bytes.fromhex(v["inputs"]["mhf_out_hex"])
    w0, w1 = derive_w0_w1(mhf_out)
    assert scalar_to_bytes(w0).hex() == v["outputs"]["w0_hex"]
    assert scalar_to_bytes(w1).hex() == v["outputs"]["w1_hex"]


