"""DEC-084 SPAKE2+ conformance vectors (Phase 7B).

Vectors live in ``mash-go/testdata/spake2plus_vectors.json`` and are
generated by ``tools/spake2plus_oracle/gen_vectors.py``. Both
implementations (mash-go and mash-py) MUST reproduce every output
byte-for-byte.

This file dispatches each vector by ``id`` to the matching mash-py
primitive and asserts the recorded outputs. Negative vectors
(``point_validation_*``) assert the expected exception is raised.

The point of running these here, beyond catching mash-py regressions,
is to *bisect* divergences against mash-go: each vector carries the
intermediate values for one stage of the algorithm, so a mismatch
localises to that stage and the bisection is at most 5 levels deep
(see Phase 7D refinement contingency in ``mash-py-tdd-plan.md``).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from mash_py.commissioning import (
    InvalidPointError,
    Verifier,
    client_public,
    compose_transcript,
    compute_L,
    confirm_macs,
    confirmation_keys,
    derive_w0_w1,
    generate_verifier,
    k_shared,
    key_chain,
    pbkdf2_mhf,
    scalar_to_bytes,
    server_public,
    validate_point,
)
from mash_py.crypto.ec import SPAKE2_M, SPAKE2_N, encode_point_uncompressed

# Vectors are produced by tools/spake2plus_oracle/gen_vectors.py and
# stored alongside mash-go's other testdata so the Go runner can
# consume them too. Walk up from this file to the repo root.
REPO_ROOT = Path(__file__).resolve().parents[4]
VECTOR_FILE = REPO_ROOT / "mash-go" / "testdata" / "spake2plus_vectors.json"


def _load_vectors() -> list[dict[str, Any]]:
    if not VECTOR_FILE.exists():
        pytest.fail(
            f"vector file missing: {VECTOR_FILE}\n"
            "Regenerate with `python tools/spake2plus_oracle/gen_vectors.py`.",
            pytrace=False,
        )
    with VECTOR_FILE.open(encoding="utf-8") as fh:
        doc = json.load(fh)
    return list(doc["vectors"])


VECTORS = _load_vectors()


def _vector_by_id(vid: str) -> dict[str, Any]:
    for v in VECTORS:
        if v["id"] == vid:
            return v
    pytest.fail(f"vector id not found: {vid}", pytrace=False)


