"""Top-level generator: YAML in, Python out.

Walks the spec inputs, normalizes them into Jinja2 template contexts,
then writes the rendered Python modules. The exposed
:func:`generate_all` returns a list of ``(path, content)`` tuples in the
order they would be written; :mod:`codegen.__main__` writes them and
the test suite uses them to drive byte-equality / drift assertions.

Determinism: features are iterated in the canonical order declared by
``protocol-versions.yaml`` (``feature_types`` slice), use cases are
sorted by ``id``. This mirrors the determinism fix mash-go landed in
commit 9b45850 — iterating a Python dict (insertion order is stable
since 3.7, but YAML key order would still leak into output) is exactly
the kind of mistake that produces flaky generators.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from jinja2 import Environment, PackageLoader, StrictUndefined

from codegen import helpers, specparse

# ---------------------------------------------------------------------------
# Header / footer that every generated module shares
# ---------------------------------------------------------------------------

_BANNER = (
    "# Generated by codegen. DO NOT EDIT.\n"
    "# Re-run via ``make generate`` (mash-py/) after editing the YAML source.\n\n"
)


# ---------------------------------------------------------------------------
# Jinja environment
# ---------------------------------------------------------------------------


def _build_env() -> Environment:
    env = Environment(
        loader=PackageLoader("codegen", "templates"),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )

    def _quote(value: object) -> str:
        # Always emit a Python string literal with double quotes — keeps
        # the diff readable even when the spec text contains apostrophes.
        # ``repr()`` would escape too aggressively (single → double quote
        # flipping) so we hand-escape: backslash, double-quote, and
        # newline / carriage-return / tab. Spec descriptions occasionally
        # contain a trailing ``\n`` from YAML folded blocks; we strip
        # surrounding whitespace too so descriptions don't carry runs of
        # blank lines into the output.
        text = str(value).strip()
        return (
            '"'
            + text.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
            + '"'
        )

    def _py_bool(value: object) -> str:
        return "True" if value else "False"

    def _pascal(name: str) -> str:
        if not name:
            return ""
        return name[0].upper() + name[1:]

    env.filters["quote"] = _quote
    env.filters["py_bool"] = _py_bool
    env.filters["pascal"] = _pascal
    def _dataclass_order(params: list[Any]) -> list[Any]:
        """Required fields first, then optional — Python dataclass ordering rule.

        Wire order (YAML order, by parameter id) is preserved within each
        group so the diff stays close to the spec, but Python forbids a
        non-default argument after a default one. Sorting is stable, so
        same-required entries keep their YAML order.
        """
        return [p for p in params if p.required] + [p for p in params if not p.required]

    env.globals.update(
        upper_snake=helpers.upper_snake,
        snake=helpers.snake_case,
        attribute_const=helpers.attribute_const,
        command_const=helpers.command_const,
        param_const=helpers.param_const,
        resp_const=helpers.resp_const,
        data_type_const=helpers.data_type_const,
        access_const=helpers.access_const,
        py_param_type=helpers.py_param_type,
        py_zero_value=helpers.py_zero_value,
        dataclass_order=_dataclass_order,
    )
    return env


# ---------------------------------------------------------------------------
# Output containers
# ---------------------------------------------------------------------------


@dataclass(slots=True)
class GeneratedFile:
    rel_path: str  # relative to mash_py/ (e.g. "features/measurement_gen.py")
    content: str


# ---------------------------------------------------------------------------
# Feature context construction
# ---------------------------------------------------------------------------


def _enum_member_lookup(
    feature: specparse.RawFeature, shared: specparse.RawShared
) -> dict[str, list[str]]:
    """Map enum name -> list of declared member names (used for default resolution)."""
    out: dict[str, list[str]] = {}
    for e in shared.enums:
        out[e.name] = [v.name for v in e.values]
    for e in feature.enums:
        out[e.name] = [v.name for v in e.values]
    return out


def _shared_imports(
    feature: specparse.RawFeature, shared: specparse.RawShared
) -> list[str]:
    """Names from ``mash_py.model.shared_gen`` that this feature references."""
    shared_names = {e.name for e in shared.enums}
    used: set[str] = set()
    for attr in feature.attributes:
        if attr.enum and attr.enum in shared_names:
            used.add(attr.enum)
        if attr.mapKeyType in shared_names:
            used.add(attr.mapKeyType)
        if attr.mapValueType in shared_names:
            used.add(attr.mapValueType)
        if attr.items:
            if attr.items.enum and attr.items.enum in shared_names:
                used.add(attr.items.enum)
            for f in attr.items.fields:
                if f.enum and f.enum in shared_names:
                    used.add(f.enum)
    for cmd in feature.commands:
        for p in (*cmd.parameters, *cmd.response):
            if p.enum and p.enum in shared_names:
                used.add(p.enum)
    return sorted(used)


def _array_object_structs(feature: specparse.RawFeature) -> list[dict[str, Any]]:
    """Collect ``items.type == 'object'`` array elements as struct contexts."""
    out: list[dict[str, Any]] = []
    seen: set[str] = set()
    for attr in feature.attributes:
        if attr.type != "array" or attr.items is None:
            continue
        if attr.items.type != "object" or not attr.items.structName:
            continue
        if attr.items.structName in seen:
            continue
        seen.add(attr.items.structName)
        fields = []
        for f in attr.items.fields:
            py_type = f.enum if f.enum else helpers._PRIMITIVE_PY_TYPE.get(f.type, "Any")  # type: ignore[attr-defined]
            fields.append(
                {
                    "name": f.name,
                    "py_name": helpers.snake_case(f.name),
                    "py_type": py_type,
                }
            )
        out.append(
            {
                "name": attr.items.structName,
                "attr_name": attr.name,
                "fields": fields,
            }
        )
    return out


def _is_simple_response(cmd: specparse.RawCommand) -> bool:
    """True when the command has no response payload of substance.

    Mirrors Go's ``isSimpleResponse``: empty response, or a single
    required ``success: bool`` field. We treat both as "no Response
    dataclass needed" — the integer-keyed map ``{1: bool}`` is enough.
    """
    if not cmd.response:
        return True
    if len(cmd.response) == 1:
        only = cmd.response[0]
        if only.name == "success" and only.type == "bool" and only.required:
            return True
    return False


def _attr_default_expr(
    attr: specparse.RawAttribute, enum_members: dict[str, list[str]]
) -> str | None:
    if attr.default is None:
        return None
    if attr.enum:
        members = enum_members.get(attr.enum, [])
        if isinstance(attr.default, str) and attr.default in members:
            return f"{attr.enum}.{attr.default}"
        if members:
            return f"{attr.enum}.{members[0]}"
    return helpers.py_literal(attr.type, attr.default)


def _attr_bound_expr(attr: specparse.RawAttribute, value: Any) -> str | None:
    if value is None:
        return None
    return helpers.py_literal(attr.type, value)


def _augment_feature_context(
    feature: specparse.RawFeature, shared: specparse.RawShared
) -> dict[str, Any]:
    enum_members = _enum_member_lookup(feature, shared)

    augmented_attrs = []
    for attr in feature.attributes:
        # Build a serializable attribute context that the template can consume.
        # We avoid mutating the dataclass so test fixtures stay round-trippable.
        attr_ctx = {
            "id": attr.id,
            "name": attr.name,
            "type": attr.type,
            "enum": attr.enum,
            "access": attr.access,
            "nullable": attr.nullable,
            "unit": attr.unit,
            "description": attr.description,
            "py_type": helpers.py_attr_type(attr),
            "default_expr": _attr_default_expr(attr, enum_members),
            "min_expr": _attr_bound_expr(attr, attr.min),
            "max_expr": _attr_bound_expr(attr, attr.max),
        }
        augmented_attrs.append(attr_ctx)

    augmented_cmds = []
    for cmd in feature.commands:
        augmented_cmds.append(
            {
                "id": cmd.id,
                "name": cmd.name,
                "description": cmd.description,
                "parameters": cmd.parameters,
                "response": cmd.response,
                "is_simple_response": _is_simple_response(cmd),
            }
        )

    feature_ctx = {
        "name": feature.name,
        "id": feature.id,
        "revision": feature.revision,
        "description": feature.description,
        "enums": feature.enums,
        "attributes": augmented_attrs,
        "commands": augmented_cmds,
    }

    # Detect ``Any`` references in any rendered type annotation so the
    # template can decide whether to ``from typing import Any``. We scan
    # attribute types, command parameter / response types, and the
    # array-element struct field types — every place ``py_attr_type`` /
    # ``py_param_type`` / the struct emitter could produce ``Any``.
    def _mentions_any(text: str) -> bool:
        return text == "Any" or "[Any" in text or ", Any" in text or "Any]" in text

    needs_any = any(_mentions_any(a["py_type"]) for a in augmented_attrs)
    if not needs_any:
        for cmd in augmented_cmds:
            for p in (*cmd["parameters"], *cmd["response"]):
                if _mentions_any(helpers.py_param_type(p)):
                    needs_any = True
                    break
            if needs_any:
                break
    if not needs_any:
        for s in _array_object_structs(feature):
            for fld in s["fields"]:
                if _mentions_any(fld["py_type"]):
                    needs_any = True
                    break
            if needs_any:
                break

    has_dataclass = bool(_array_object_structs(feature)) or any(
        c["parameters"] or (c["response"] and not c["is_simple_response"])
        for c in augmented_cmds
    )

    return {
        "feature": feature_ctx,
        "feature_dir": specparse.feature_dir_name(feature.name),
        "shared_imports": _shared_imports(feature, shared),
        "array_object_structs": _array_object_structs(feature),
        "revision_const": helpers.feature_revision_const(feature.name),
        "needs_any": needs_any,
        "has_dataclass": has_dataclass,
        "has_commands": bool(augmented_cmds),
        "has_local_enums": bool(feature.enums),
    }


