def _resolve_use_cases(
    use_cases: list[specparse.RawUseCase],
    features: list[specparse.RawFeature],
) -> list[dict[str, Any]]:
    """Resolve feature/attribute/command names against the spec manifest.

    Mirrors ``mash-go/pkg/usecase/resolve.go``: every name referenced
    inside a use case scenario is replaced with its numeric id from the
    spec manifest. An unresolvable name is a hard error (the YAML drifted).
    """
    feat_idx: dict[str, specparse.RawFeature] = {f.name: f for f in features}
    out: list[dict[str, Any]] = []
    for uc in use_cases:
        scenarios = []
        for s in uc.scenarios:
            feats = []
            for fr in s.features:
                feat_def = feat_idx.get(fr.feature)
                if feat_def is None:
                    raise ValueError(
                        f"use case {uc.name}.{s.name}: unknown feature {fr.feature!r}"
                    )
                attr_idx = {a.name: a.id for a in feat_def.attributes}
                cmd_idx = {c.name: c.id for c in feat_def.commands}
                attrs = []
                for a in fr.attributes:
                    aid = attr_idx.get(a.name)
                    if aid is None:
                        raise ValueError(
                            f"use case {uc.name}.{s.name}.{fr.feature}: "
                            f"unknown attribute {a.name!r}"
                        )
                    attrs.append({"name": a.name, "attr_id": aid, "required_value": a.requiredValue})
                cmds = []
                for cname in fr.commands:
                    cid = cmd_idx.get(cname)
                    if cid is None:
                        raise ValueError(
                            f"use case {uc.name}.{s.name}.{fr.feature}: "
                            f"unknown command {cname!r}"
                        )
                    cmds.append({"name": cname, "command_id": cid})
                feats.append(
                    {
                        "feature": fr.feature,
                        "feature_id": feat_def.id,
                        "required": fr.required,
                        "attributes": attrs,
                        "commands": cmds,
                        "subscribe": fr.subscribe,
                    }
                )
            scenarios.append(
                {
                    "bit": s.bit,
                    "name": s.name,
                    "description": s.description,
                    "requires": s.requires,
                    "requiresAny": s.requiresAny,
                    "endpointTypes": s.endpointTypes,
                    "features": feats,
                }
            )
        out.append(
            {
                "name": uc.name,
                "id": uc.id,
                "fullName": uc.fullName,
                "description": _normalize_description(uc.description),
                "specVersion": uc.specVersion,
                "major": uc.major,
                "minor": uc.minor,
                "endpointTypes": uc.endpointTypes,
                "scenarios": scenarios,
                "commands": uc.commands,
            }
        )
    return out


_MULTI_WS = re.compile(r"\s+")


def _normalize_description(text: str) -> str:
    """Collapse internal whitespace so YAML folded blocks don't create diff churn."""
    return _MULTI_WS.sub(" ", text).strip()


