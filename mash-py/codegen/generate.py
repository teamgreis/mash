# Top-level orchestration
# ---------------------------------------------------------------------------


def generate_all(
    features_dir: Path | str,
    usecases_dir: Path | str,
    *,
    protocol_path: Path | str | None = None,
    shared_path: Path | str | None = None,
    version: str = "1.0",
) -> list[GeneratedFile]:
    """Build every generated module for the given spec inputs.

    ``protocol_path`` defaults to ``<features_dir>/protocol-versions.yaml``;
    ``shared_path`` defaults to ``<features_dir>/_shared/<version>.yaml``.
    """
    features_dir = Path(features_dir)
    usecases_dir = Path(usecases_dir)
    if protocol_path is None:
        protocol_path = features_dir / "protocol-versions.yaml"
    if shared_path is None:
        shared_path = features_dir / "_shared" / f"{version}.yaml"

    protocol = specparse.load_protocol_version(protocol_path, version)
    shared = specparse.load_shared(shared_path)
    features = specparse.load_all_features(features_dir, protocol)
    use_cases = specparse.load_all_use_cases(usecases_dir)

    specparse.validate_feature_ids(protocol.feature_types, features)

    env = _build_env()
    output: list[GeneratedFile] = []

    # ---- model/feature_type_gen.py ----
    tmpl = env.get_template("feature_type.py.j2")
    body = tmpl.render(types=protocol.feature_types)
    output.append(
        GeneratedFile(rel_path="model/feature_type_gen.py", content=_BANNER + body)
    )

    # ---- model/endpoint_type_gen.py ----
    tmpl = env.get_template("endpoint_type.py.j2")
    body = tmpl.render(types=protocol.endpoint_types)
    output.append(
        GeneratedFile(rel_path="model/endpoint_type_gen.py", content=_BANNER + body)
    )

    # ---- model/use_case_type_gen.py ----
    tmpl = env.get_template("use_case_type.py.j2")
    body = tmpl.render(types=protocol.use_case_types)
    output.append(
        GeneratedFile(rel_path="model/use_case_type_gen.py", content=_BANNER + body)
    )

    # ---- model/shared_gen.py ----
    tmpl = env.get_template("shared.py.j2")
    body = tmpl.render(shared=shared)
    output.append(GeneratedFile(rel_path="model/shared_gen.py", content=_BANNER + body))

    # ---- features/<name>_gen.py ----
    feat_tmpl = env.get_template("feature.py.j2")
    for feat in features:
        ctx = _augment_feature_context(feat, shared)
        body = feat_tmpl.render(**ctx)
        rel = f"features/{helpers.feature_module_name(feat.name)}_gen.py"
        output.append(GeneratedFile(rel_path=rel, content=_BANNER + body))

    # ---- usecase/definitions_gen.py ----
    if use_cases:
        uc_ctx = _resolve_use_cases(use_cases, features)
        uc_tmpl = env.get_template("use_case.py.j2")
        body = uc_tmpl.render(use_cases=uc_ctx, spec_version=version)
        output.append(
            GeneratedFile(rel_path="usecase/definitions_gen.py", content=_BANNER + body)
        )

    return output


def write_outputs(outputs: list[GeneratedFile], target_root: Path | str) -> list[Path]:
    """Write each :class:`GeneratedFile` under ``target_root``.

    Returns the absolute paths of files written. Existing files are
    overwritten only if their content differs (cheap idempotency).
    """
    root = Path(target_root)
    written: list[Path] = []
    for gf in outputs:
        dest = root / gf.rel_path
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.exists() and dest.read_text(encoding="utf-8") == gf.content:
            written.append(dest)
            continue
        dest.write_text(gf.content, encoding="utf-8")
        written.append(dest)
    return written
